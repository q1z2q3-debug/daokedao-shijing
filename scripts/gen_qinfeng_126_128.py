def render(d):
    s = [f"# 第{d['zh']}篇　{d['title']}", "", f"> 秦风 · 之{d['vol']}　SJ{d['no']}", "", "## 一　解题", "", d['jie'].strip(), "", "## 二　经文", ""]
    for i, st in enumerate(d['stanzas'], 1):
        s.append(f"第{'一二三四五'[i-1]}章")
        s.append("")
        for line in st:
            s.append(f"> {line}")
            s.append(">")
        s.pop()
        s.append("")
    s += [f"**分章**：{d['lines']}。", "", "## 三　韵读", ""]
    s += [f"- {x}" for x in d['yun']]
    s += ["", "**读法**：三章由器入念，韵随物转；**器名越密，念句越短。**", "", "## 四　字义与名物", ""]
    s += [f"- {x}" for x in d['zi']]
    s += ["", "## 五　今译", ""]
    for x in d['yi']:
        s += [x, ""]
    s += ["## 六　章旨", ""]
    s += [f"- {x}" for x in d['zhang']]
    s += ["", "## 七　诗教", ""]
    s += [f"- {x}" for x in d['jiao']]
    s += ["", "## 八　分寸与边界", ""]
    s += [f"- {x}" for x in d['bian']]
    s += ["", "## 九　存疑", ""]
    s += [f"- {x}" for x in d['cun']]
    s += ["", "## 十　跨典", ""]
    s += [f"- {x}" for x in d['kua']]
    s += ["", "## 十一　双卡与图", "", "**六对**：", "", "| 正 | 误 |", "|---|---|"]
    for a, b in d['pairs']:
        s.append(f"| {a} | {b} |")
